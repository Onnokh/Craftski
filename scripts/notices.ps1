# Writes THIRD-PARTY.md: the fonts and icons bundled in craftski.exe, then each Rust crate built
# into the Windows exe with its license, from `cargo metadata`. Run it after a dependency changes.
$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

$cargo = (Get-Command cargo -ErrorAction SilentlyContinue).Source
if (-not $cargo) { $cargo = Join-Path $env:USERPROFILE '.cargo\bin\cargo.exe' }
$meta = & $cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-msvc | ConvertFrom-Json
$root = $meta.resolve.root
$byId = @{}
foreach ($node in $meta.resolve.nodes) { $byId[$node.id] = $node }

# Walk normal dependencies only: build scripts and tests don't ship in the exe.
$seen = @{}
$queue = [System.Collections.Generic.Queue[string]]::new()
$queue.Enqueue($root)
while ($queue.Count) {
    foreach ($dep in $byId[$queue.Dequeue()].deps) {
        if (-not ($dep.dep_kinds | Where-Object { $null -eq $_.kind })) { continue }
        if ($seen.ContainsKey($dep.pkg)) { continue }
        $seen[$dep.pkg] = $true
        $queue.Enqueue($dep.pkg)
    }
}
$crates = $meta.packages | Where-Object { $seen.ContainsKey($_.id) } | Sort-Object name, version

$lines = @(
    '# Third-party software in Craftski'
    ''
    'Craftski is not affiliated with or endorsed by Blizzard Entertainment or TradeSkillMaster.'
    'World of Warcraft is a trademark of Blizzard Entertainment.'
    ''
    'Craftski bundles no game art. On first use it downloads the item icons and interface art it'
    'shows from wago.tools and Wowhead, and it reads prices from TSM''s AppHelper file or TSM''s'
    'public data.'
    ''
    '## Bundled assets'
    ''
    '| Asset | License |'
    '| --- | --- |'
    '| IBM Plex Sans (`assets/fonts`) | SIL Open Font License 1.1, see `assets/fonts/IBMPlexSans-OFL.txt` |'
    '| Rune Icons (`assets/icons`) | Apache License 2.0, see `assets/icons/LICENSE` |'
    ''
    "## Rust crates ($($crates.Count))"
    ''
    'Generated by `scripts/notices.ps1` from `cargo metadata`. Each crate''s license text is in its source.'
    ''
    '| Crate | Version | License |'
    '| --- | --- | --- |'
)
foreach ($c in $crates) {
    $license = if ($c.license) { $c.license } else { 'see crate' }
    $name = if ($c.repository) { "[$($c.name)]($($c.repository))" } else { $c.name }
    $lines += "| $name | $($c.version) | $license |"
}
[IO.File]::WriteAllText((Join-Path (Get-Location) 'THIRD-PARTY.md'), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Host "THIRD-PARTY.md: $($crates.Count) crates"
